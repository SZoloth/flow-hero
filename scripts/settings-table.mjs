import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const START = '<!-- settings:start (generated by pnpm settings-table; edit src/patch.ts instead) -->';
export const END = '<!-- settings:end -->';

const cell = (s) => String(s).replace(/\|/g, '\\|');

function range(s) {
  switch (s.kind) {
    case 'number':
      return `${s.min} to ${s.max}${s.step >= 1 ? ', whole numbers' : ''}`;
    case 'colors':
      return `${s.minItems} to ${s.maxItems} hex colours`;
    case 'color':
      return 'hex colour';
    case 'enum':
      return s.options.map((o) => `\`${o}\``).join(', ');
    case 'text':
      return `text, up to ${s.maxLength} characters`;
  }
}

const fmt = (v) => (Array.isArray(v) ? v.map((c) => `\`${c}\``).join(' ') : `\`${typeof v === 'string' ? v : JSON.stringify(v)}\``);

export function renderTable(settings) {
  const rows = settings.map((s) => `| \`${s.path}\` | ${cell(range(s))} | ${fmt(s.default)} | ${cell(s.help)} |`);
  return [START, '| Setting | Range | Default (ember) | What it does |', '| --- | --- | --- | --- |', ...rows, END].join('\n');
}

export function replaceTable(readme, table) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error('README is missing the settings markers');
  return readme.slice(0, a) + table + readme.slice(b + END.length);
}

async function loadSettings() {
  const out = await build({ entryPoints: ['src/patch.ts'], bundle: true, format: 'esm', write: false });
  const url = `data:text/javascript;base64,${Buffer.from(out.outputFiles[0].contents).toString('base64')}`;
  return (await import(url)).SETTINGS;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const readme = readFileSync('README.md', 'utf8');
  const next = replaceTable(readme, renderTable(await loadSettings()));
  if (process.argv.includes('--write')) {
    writeFileSync('README.md', next);
    console.log('README settings table updated');
  } else if (next !== readme) {
    console.error('README settings table is out of date. Run pnpm settings-table.');
    process.exit(1);
  } else {
    console.log('README settings table is up to date');
  }
}
